import { File, FileArchive, FileAudio, FileImage, FileText, FileType2, FileVideo } from "lucide-react";
import { useEffect } from "react";
import type { FileInfo } from "../lib/bindings/FileInfo";
import type { FormatFamily } from "../lib/bindings/FormatFamily";
import { api } from "../lib/api";
import { useApp } from "../store/app";
import { cn } from "./ui/primitives";

const ICONS: Record<FormatFamily | "unknown", typeof File> = {
  image: FileImage,
  pdf: FileText,
  audio: FileAudio,
  video: FileVideo,
  archive: FileArchive,
  document: FileType2,
  unknown: File,
};

export function familyColor(family: FormatFamily | null): string {
  return `var(--fam-${family ?? "unknown"})`;
}

export function FamilyIcon({ family, className }: { family: FormatFamily | null; className?: string }) {
  const Icon = ICONS[family ?? "unknown"];
  return <Icon className={className} style={{ color: familyColor(family) }} aria-hidden />;
}

// Thumbnails are generated by the backend; keep only a few in flight.
const MAX_IN_FLIGHT = 3;
let inFlight = 0;
const waiting: Array<() => void> = [];
const requested = new Set<string>();

function schedule(task: () => Promise<void>) {
  const run = () => {
    inFlight += 1;
    task().finally(() => {
      inFlight -= 1;
      waiting.shift()?.();
    });
  };
  if (inFlight < MAX_IN_FLIGHT) run();
  else waiting.push(run);
}

function wantsThumbnail(file: FileInfo) {
  return !file.issue && (file.family === "image" || file.family === "pdf") && file.format !== "avif";
}

export function Thumbnail({ file, size = 44 }: { file: FileInfo; size?: number }) {
  const url = useApp((s) => s.thumbnails[file.id]);
  const setThumbnail = useApp((s) => s.setThumbnail);

  useEffect(() => {
    if (!wantsThumbnail(file) || requested.has(file.id)) return;
    requested.add(file.id);
    schedule(() =>
      api
        .thumbnail(file.id)
        .then((data) => setThumbnail(file.id, data))
        .catch(() => setThumbnail(file.id, null)),
    );
  }, [file, setThumbnail]);

  return (
    <div
      className={cn("relative flex shrink-0 items-center justify-center overflow-hidden rounded-xl border border-border")}
      style={{
        width: size,
        height: size,
        background: `color-mix(in oklab, ${familyColor(file.family)} 12%, var(--surface))`,
      }}
    >
      {url ? (
        <img src={url} alt="" className="size-full object-cover" draggable={false} />
      ) : (
        <FamilyIcon family={file.family} className="size-5" />
      )}
    </div>
  );
}
